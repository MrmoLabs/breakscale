/**
 * Chinese copy for the 24 example tasks: the goal, one line per step, the
 * "What you learned" line, and the live figure labels beside each step.
 * Keys are the preset ids from src/content/exampleTasks.ts, which stay
 * English on the wire; only what TaskCard renders goes through taskCopy().
 *
 * `steps` holds the step text by index and REPLACES the English text whole:
 * some steps are built by raise(), whose English text embeds a number that
 * varies with the load, so an index-keyed replacement cannot be byte-matched
 * against it. Each Chinese step text is self-contained and carries its own
 * number, read from the step's load condition.
 *
 * `figs` holds the figure labels by step index, each an array in the step's
 * own figure order. A missing entry or a short array falls back to the
 * English label for that figure.
 *
 * Node names follow the canvas labels (zh/labels.ts), field names follow the
 * inspector labels (zh/inspector.ts), and the fault buttons keep the app's
 * own words (弄崩, 变慢, 修复, 抖动). Numbers, units and p99 stay as stored.
 */

export interface TaskCopyZh {
  readonly goal: string;
  readonly learned: string;
  /** Step text by index, replacing the English text wholesale. */
  readonly steps: readonly string[];
  /** Figure labels by step index, then in the step's own figure order. */
  readonly figs?: Readonly<Record<number, readonly string[]>>;
}

